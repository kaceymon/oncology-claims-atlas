"""Builds data/gen_*.js from the public source files fetched by tools/fetch_sources.sh.

Usage: python -I tools/build_data.py <download-dir>

Only public-domain or freely licensed code sets are emitted:
  NUCC provider taxonomy, ICD-10-CM (CDC), HCPCS Level II (CMS, minus ADA CDT D-codes),
  CMS Place of Service. CPT (AMA), CDT (ADA), X12 and NUBC text is never copied.
"""
import csv, html, json, os, re, sys
from datetime import date

SRC = sys.argv[1] if len(sys.argv) > 1 else "."
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data")
TODAY = date.today().strftime("%Y%m%d")


def emit(name, var, payload):
    path = os.path.join(OUT, f"gen_{name}.js")
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"// generated by tools/build_data.py - do not edit\nOCA.load({json.dumps(var)}, ")
        json.dump(payload, f, ensure_ascii=False, separators=(",", ":"))
        f.write(");\n")
    print(f"{path}: {len(payload['rows'])} rows, {os.path.getsize(path) // 1024} KB")


# ---------- NUCC provider taxonomy ----------
ONC_PROVIDER = re.compile(r"oncolog|hematolog|radiation|cancer|tumor|hospice|palliative|infusion|"
                          r"nuclear|radiolog|patholog|genetic|bone marrow|transplant|blood bank|"
                          r"pharmac|medical physic|dosimetr", re.I)

def build_providers():
    path = os.path.join(SRC, "nucc_taxonomy.csv")
    if not os.path.exists(path):
        path = next(os.path.join(SRC, p) for p in os.listdir(SRC) if p.startswith("nucc_taxonomy"))
    rows = []
    with open(path, encoding="utf-8-sig", errors="replace") as f:
        for r in csv.DictReader(f):
            title = r["Display Name"].strip() or " - ".join(x for x in (r["Classification"], r["Specialization"]) if x)
            text = r["Definition"].strip()
            hay = " ".join((r["Grouping"], r["Classification"], r["Specialization"], title))
            rows.append([r["Code"].strip(), title, text, r["Grouping"].strip(), r["Classification"].strip(),
                         r["Specialization"].strip(), r["Section"].strip(), 1 if ONC_PROVIDER.search(hay) else 0])
    emit("providers", "provider", {
        "source": {"name": "NUCC Health Care Provider Taxonomy v26.1", "url": "https://www.nucc.org/index.php/code-sets-mainmenu-41/provider-taxonomy-mainmenu-40"},
        "cols": ["code", "title", "text", "grouping", "classification", "specialization", "section", "onc"],
        "rows": rows})


# ---------- ICD-10-CM (neoplasm chapter + oncology-adjacent codes) ----------
ICD_BLOCKS = [  # chapter 2 blocks, checked in order
    ("C7A", "C7A", "Malignant neuroendocrine tumors"), ("C7B", "C7B", "Secondary neuroendocrine tumors"),
    ("D3A", "D3A", "Benign neuroendocrine tumors"),
    ("C00", "C14", "Lip, oral cavity, pharynx"), ("C15", "C26", "Digestive organs"),
    ("C30", "C39", "Respiratory and intrathoracic"), ("C40", "C41", "Bone and articular cartilage"),
    ("C43", "C44", "Melanoma and other skin"), ("C45", "C49", "Mesothelial and soft tissue"),
    ("C50", "C50", "Breast"), ("C51", "C58", "Female genital organs"), ("C60", "C63", "Male genital organs"),
    ("C64", "C68", "Urinary tract"), ("C69", "C72", "Eye, brain, CNS"), ("C73", "C75", "Thyroid and endocrine"),
    ("C76", "C80", "Ill-defined, secondary, unspecified sites"), ("C81", "C96", "Lymphoid, hematopoietic"),
    ("D00", "D09", "In situ neoplasms"), ("D10", "D36", "Benign neoplasms"),
    ("D37", "D48", "Uncertain behavior"), ("D49", "D49", "Unspecified behavior"),
]
ICD_SUPPORT = ("Z51.0", "Z51.1", "Z85", "Z86.0", "Z80", "Z15", "Z17", "Z19", "Z92.2", "Z92.3", "Z08", "Z09",
               "Z45.2", "Z79.6", "Z00.6", "Z40.0", "Z90.1", "Z95.828", "Z52.0", "Z94.8", "Z94.84",
               "D61.81", "D63.0", "D64.81", "D70.1", "D69.59", "D70.9", "E88.3", "R53.0", "R11.2", "R18.0",
               "J91.0", "G62.0", "T45.1X5", "T80.81", "T86.0", "T66", "L58", "K12.3", "N30.4", "R50.81",
               "Y84.2", "Y63.2", "D47.Z2", "Z51.5", "Z51.89", "Z71.89", "Z31.6", "Z31.84")

def icd_dot(c):
    return c if len(c) <= 3 else c[:3] + "." + c[3:]

def icd_block(c):
    head = c[:3]
    for lo, hi, name in ICD_BLOCKS:
        if lo == hi == head:
            return name
    for lo, hi, name in ICD_BLOCKS:
        if lo != hi and lo <= head <= hi and head not in ("C7A", "C7B", "D3A"):
            return name
    return None

def build_icd():
    path = None
    for root, _, files in os.walk(SRC):
        for fn in files:
            if re.match(r"icd10cm[-_]order[-_]\d{4}\.txt$", fn, re.I):
                path = os.path.join(root, fn)
    rows = []
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            code = line[6:13].strip()
            billable = line[14] == "1"
            long_desc = line[77:].strip()
            d = icd_dot(code)
            in_chapter = code[0] == "C" or (code[0] == "D" and code[1] in "01234")
            block = icd_block(code) if in_chapter else None
            if not (in_chapter and block) and not any(d.startswith(p) for p in ICD_SUPPORT):
                continue
            rows.append([d, long_desc, 1 if billable else 0, block or "Oncology-adjacent (Z/R/D/T/E codes)"])
    emit("icd10", "icd10", {
        "source": {"name": "ICD-10-CM FY2027 (Oct 1, 2026 - Sep 30, 2027), CDC/NCHS", "url": "https://www.cdc.gov/nchs/icd/icd-10-cm/files.html"},
        "cols": ["code", "title", "billable", "block"], "rows": rows})


# ---------- HCPCS Level II ----------
HCPCS_SERIES = {
    "A": "Transport, medical/surgical supplies, radiopharmaceuticals", "B": "Enteral and parenteral therapy",
    "C": "Hospital OPPS temporary codes", "E": "Durable medical equipment", "G": "Temporary procedures / professional services",
    "H": "Behavioral health (Medicaid)", "J": "Drugs (non-oral) and chemotherapy", "K": "DME MAC temporary codes",
    "L": "Orthotics and prosthetics", "M": "Quality measures and other services", "P": "Pathology and laboratory",
    "Q": "Temporary codes (incl. biosimilars, CAR-T, skin substitutes)", "R": "Diagnostic radiology",
    "S": "Private payer temporary codes", "T": "State Medicaid codes", "U": "Laboratory (CLFS)", "V": "Vision and hearing",
}
COVERAGE = {"C": "Carrier judgment", "D": "Special coverage instructions apply", "I": "Not payable by Medicare",
            "M": "Non-covered by Medicare", "S": "Non-covered by Medicare statute"}
ONC_HCPCS = re.compile(
    r"chemo|antineoplastic|oncolog|cancer|tumou?r|carcinoma|lymphoma|leukemia|myeloma|melanoma|sarcoma|neoplas|"
    r"filgrastim|pegfilgrastim|sargramostim|epoetin|darbepoetin|ondansetron|granisetron|palonosetron|aprepitant|"
    r"fosnetupitant|rolapitant|leucovorin|levoleucovorin|mesna|dexrazoxane|amifostine|rasburicase|zoledronic|"
    r"denosumab|pamidronate|rituximab|trastuzumab|bevacizumab|pembrolizumab|nivolumab|cetuximab|t-cell|"
    r"brachytherapy|radiation|radiopharm|radioligand|lutetium|radium|iodine i-131|yttrium|strontium|"
    r"infusion pump|biosimilar|bcg|interferon|interleukin|hydroxyurea|methotrexate|capecitabine|"
    r"temozolomide|cyclophosphamide|etoposide|tamoxifen|anastrozole|letrozole|leuprolide|goserelin|"
    r"triptorelin|degarelix|histrelin|octreotide|lanreotide|fulvestrant|wig|mastectomy|breast prosthe|"
    r"port|reservoir|bone marrow|stem cell|apheresis|tumor treat", re.I)

def build_hcpcs():
    folder = os.path.join(SRC, "hcpcs")
    path = next(os.path.join(folder, p) for p in os.listdir(folder) if re.search(r"ANWEB_\d+\.txt$", p))
    procs, mods = {}, {}
    with open(path, encoding="latin-1") as f:
        for line in f:
            line = line.rstrip("\r\n").ljust(320)
            rid = line[10]
            code, mod = line[0:5].strip(), line[3:5].strip()
            long_desc = line[11:91].strip()
            if rid == "3":
                procs[code] = {"desc": long_desc, "short": line[91:119].strip(), "cov": line[229].strip(),
                               "betos": line[256:259].strip(), "added": line[268:276].strip(),
                               "eff": line[276:284].strip(), "term": line[284:292].strip()}
                last = procs[code]
            elif rid == "4":
                last["desc"] += " " + long_desc
            elif rid == "7":
                mods[mod] = {"desc": long_desc, "term": line[284:292].strip()}
                last = mods[mod]
            elif rid == "8":
                last["desc"] += " " + long_desc
    rows = []
    for code, p in sorted(procs.items()):
        if code[0] == "D" or code[0].isdigit():  # CDT (ADA) / CPT (AMA) are copyrighted
            continue
        if p["term"] and p["term"] <= TODAY:
            continue
        desc = re.sub(r"\s+", " ", p["desc"]).strip()
        onc = 1 if (code.startswith("J9") or ONC_HCPCS.search(desc)) else 0
        rows.append([code, desc, HCPCS_SERIES.get(code[0], "Other"), COVERAGE.get(p["cov"], ""), p["added"], onc])
    emit("hcpcs", "hcpcs", {
        "source": {"name": "CMS HCPCS Level II, October 2026 quarterly file", "url": "https://www.cms.gov/medicare/coding-billing/healthcare-common-procedure-system/quarterly-update"},
        "cols": ["code", "title", "series", "medicare", "added", "onc"], "rows": rows})
    mrows = []
    for m, p in sorted(mods.items()):
        if p["term"] and p["term"] <= TODAY:
            continue
        mrows.append([m, re.sub(r"\s+", " ", p["desc"]).strip()])
    # CPT modifiers (numeric) appear in the CMS file only by number; keep Level II alpha modifiers
    mrows = [r for r in mrows if not r[0].isdigit()]
    emit("modifiers", "modifier", {
        "source": {"name": "CMS HCPCS Level II modifiers, October 2026", "url": "https://www.cms.gov/medicare/coding-billing/healthcare-common-procedure-system/quarterly-update"},
        "cols": ["code", "title"], "rows": mrows})


# ---------- Place of Service ----------
def build_pos():
    raw = open(os.path.join(SRC, "pos.html"), "rb").read()
    try:
        t = raw.decode("utf-8")
    except UnicodeDecodeError:
        t = raw.decode("cp1252", errors="replace")
    rows = []
    for r in re.findall(r"<tr[^>]*>(.*?)</tr>", t, re.S):
        cells = [re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", c))).strip()
                 for c in re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", r, re.S)]
        if len(cells) >= 3 and re.fullmatch(r"\d\d", cells[0]):
            name = cells[1].rstrip("*").replace("ServiceProvider", "Service Provider")
            rows.append([cells[0], name, cells[2]])
    emit("pos", "pos", {
        "source": {"name": "CMS Place of Service Code Set", "url": "https://www.cms.gov/medicare/coding-billing/place-of-service-codes/code-sets"},
        "cols": ["code", "title", "text"], "rows": rows})


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    build_providers()
    build_icd()
    build_hcpcs()
    build_pos()
