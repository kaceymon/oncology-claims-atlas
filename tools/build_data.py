"""Builds data/gen_*.js from the public source files fetched by tools/fetch_sources.sh.

Usage: python -I tools/build_data.py <download-dir>

Only public-domain or freely licensed code sets are emitted:
  NUCC provider taxonomy, ICD-10-CM (CDC), HCPCS Level II (CMS, minus ADA CDT D-codes),
  CMS Place of Service. CPT (AMA), CDT (ADA), X12 and NUBC text is never copied.
"""
import csv, html, json, os, re, sys
from datetime import date

SRC = sys.argv[1] if len(sys.argv) > 1 else "."
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data")
TODAY = date.today().strftime("%Y%m%d")


def emit(name, var, payload):
    path = os.path.join(OUT, f"gen_{name}.js")
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"// generated by tools/build_data.py - do not edit\nOCA.load({json.dumps(var)}, ")
        json.dump(payload, f, ensure_ascii=False, separators=(",", ":"))
        f.write(");\n")
    print(f"{path}: {len(payload['rows'])} rows, {os.path.getsize(path) // 1024} KB")


# ---------- NUCC provider taxonomy ----------
ONC_PROVIDER = re.compile(r"oncolog|hematolog|radiation|cancer|tumor|hospice|palliative|infusion|"
                          r"nuclear|radiolog|patholog|genetic|bone marrow|transplant|blood bank|"
                          r"pharmac|medical physic|dosimetr", re.I)

def build_providers():
    path = os.path.join(SRC, "nucc_taxonomy.csv")
    if not os.path.exists(path):
        path = next(os.path.join(SRC, p) for p in os.listdir(SRC) if p.startswith("nucc_taxonomy"))
    rows = []
    with open(path, encoding="utf-8-sig", errors="replace") as f:
        for r in csv.DictReader(f):
            title = r["Display Name"].strip() or " - ".join(x for x in (r["Classification"], r["Specialization"]) if x)
            text = r["Definition"].strip()
            hay = " ".join((r["Grouping"], r["Classification"], r["Specialization"], title))
            rows.append([r["Code"].strip(), title, text, r["Grouping"].strip(), r["Classification"].strip(),
                         r["Specialization"].strip(), r["Section"].strip(), 1 if ONC_PROVIDER.search(hay) else 0])
    emit("providers", "provider", {
        "source": {"name": "NUCC Health Care Provider Taxonomy v26.1", "url": "https://www.nucc.org/index.php/code-sets-mainmenu-41/provider-taxonomy-mainmenu-40"},
        "cols": ["code", "title", "text", "grouping", "classification", "specialization", "section", "onc"],
        "rows": rows})


# ---------- ICD-10-CM (neoplasm chapter + oncology-adjacent codes) ----------
