    ("C30", "C39", "Respiratory and intrathoracic"), ("C40", "C41", "Bone and articular cartilage"),
    ("C43", "C44", "Melanoma and other skin"), ("C45", "C49", "Mesothelial and soft tissue"),
    ("C50", "C50", "Breast"), ("C51", "C58", "Female genital organs"), ("C60", "C63", "Male genital organs"),
    ("C64", "C68", "Urinary tract"), ("C69", "C72", "Eye, brain, CNS"), ("C73", "C75", "Thyroid and endocrine"),
