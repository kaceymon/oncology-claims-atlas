const PFS_LOOKUP = ["CMS - Physician Fee Schedule look-up (RVUs, indicators)", "https://www.cms.gov/medicare/physician-fee-schedule/search"];

function cpt(group, note, rel) {
  return ([code, label, extra]) => ({
    code, title: label, tags: ["cpt", group], cptGroup: group,
    summary: `${group} – ${label}`,
    body: `<p>${label}.${extra ? " " + extra : ""}</p>${note ? `<p>${note}</p>` : ""}
<p class="muted small">CPT® is a registered trademark of the American Medical Association. This label is a plain-language summary, not the official descriptor.</p>`,
    src: [AMA, PFS_LOOKUP], rel: rel || [],
  });
}

